/// App entry point: connects to Firebase, then starts BahinKo.
/// Everything else lives in app.dart and screens/.
library;

import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'package:bahinko/app.dart';
import 'package:bahinko/services/app_lock_service.dart';
import 'package:bahinko/services/auth_service.dart';
import 'package:bahinko/services/firestore_group_service.dart';
import 'package:bahinko/services/group_service.dart';
import 'package:bahinko/services/secure_store.dart';
import 'package:bahinko/services/settings_service.dart';
// Generated by `flutterfire configure`. NOT in git (see .gitignore):
// teammates get this file privately or run flutterfire configure themselves.
import 'package:bahinko/firebase_options.dart';

/// `async` because connecting to Firebase takes time; `await` makes the app
/// wait until Firebase is ready before the first screen appears.
Future<void> main() async {
  // Required before any `await` in main(): Firebase talks to native code
  // through platform channels, which need the Flutter engine running first.
  WidgetsFlutterBinding.ensureInitialized();

  // Picks the right keys for the current platform (Android, web, Windows).
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Firebase remembers the sign-in on this device, so returning users
  // skip onboarding and go straight to the PIN screen.
  await AuthService.instance.restoreSession();

  // Use the real database. (Tests skip main(), so they keep the in-memory
  // sample service and never touch Firebase.)
  GroupService.instance = FirestoreGroupService();

  // Keep the PIN hash in the phone's encrypted storage (tests use memory).
  AppLockService.instance = AppLockService(store: SecureStore());

  // Load saved settings (app lock on/off, fingerprint, Profile toggles).
  await SettingsService.instance.load();

  final auth = AuthService.instance;
  runApp(
    BahinKoApp(
      signedIn: auth.isSignedIn,
      needsName: auth.isSignedIn && auth.displayName == null,
      lockOnStart: SettingsService.instance.appLockEnabled,
    ),
  );
}
